public static class RunProgress
{
    public static int   Level      = 1;
    public static float HpMult     = 1f;
    public static float AtkMult    = 1f;
    public static int   EnemyCount = 1;

    public static void Reset()
    {
        Level      = 1;
        HpMult     = 1f;
        AtkMult    = 1f;
        EnemyCount = 1;
    }
}
